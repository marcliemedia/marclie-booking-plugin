	public static function isValid( string $code ): bool {
		return in_array( strtoupper( $code ), self::CODES, true );
	}

	/**
	 * Code => localized name, sorted by name.
	 *
	 * @return array<string, string>
	 */
	public static function names( string $lang ): array {
		$lang   = LanguageAdapter::normalize( $lang ) ?? LanguageAdapter::DEFAULT;
		$locale = 'en' === $lang ? 'en_GB' : 'hr_HR';
		$names  = array();
		foreach ( self::CODES as $code ) {
			$name           = class_exists( \Locale::class ) ? (string) \Locale::getDisplayRegion( '-' . $code, $locale ) : '';
			$names[ $code ] = '' !== $name && $name !== $code ? $name : $code;
		}

		if ( class_exists( \Collator::class ) ) {
			$collator = new \Collator( $locale );
			uasort( $names, static fn( string $a, string $b ): int => (int) $collator->compare( $a, $b ) );
		} else {
			asort( $names, SORT_NATURAL | SORT_FLAG_CASE );
		}

		return $names;
	}
}
